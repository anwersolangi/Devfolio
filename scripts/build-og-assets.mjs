// Builds the static share images that live in /public:
//   1. public/og-image.png — the site-wide default card
//   2. public/blog/*-cover.png — PNG copies of the hand-drawn SVG blog covers,
//      because Facebook, LinkedIn and X don't render SVG in og:image.
//
//   3. public/blog/*-dark.svg — dark-theme copies of every blog SVG (covers
//      and diagrams), recoloured from the light palette. ThemedImage shows
//      the one that matches the active theme.
//
// Run after adding a blog post or changing the default card:
//   npm run og:assets
//
// Per-app, per-tool and per-reel cards are generated by the opengraph-image.js
// routes at build time and don't need this script.
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";
import { ImageResponse } from "next/dist/compiled/@vercel/og/index.node.js";
import { ogCard, loadOgFonts, loadImage, OG_SIZE } from "../src/lib/og-card.js";

const PUBLIC = path.join(process.cwd(), "public");

// 1. Default card.
const fonts = await loadOgFonts();
const screen = await loadImage(
  "/reels/covers/live-stock-chart-react-native-self-drawing-svg-price-ticker-reel.jpg",
);
const card = new ImageResponse(
  ogCard({
    kicker: "React Native developer · Karachi, Pakistan",
    title: "Anwer Solangi",
    subtitle:
      "iOS and Android apps for founders worldwide. 50+ projects delivered, 100K+ app downloads.",
    footer: "anwersolangi.com",
    screen,
  }),
  { ...OG_SIZE, fonts },
);
await writeFile(path.join(PUBLIC, "og-image.png"), Buffer.from(await card.arrayBuffer()));
console.log("wrote public/og-image.png");

// 2. Blog covers. The SVGs use system fonts, so render on a machine that has
// them (any Mac); the PNGs are committed.
const blogDir = path.join(PUBLIC, "blog");
for (const file of (await readdir(blogDir)).filter((f) => f.endsWith("-cover.svg"))) {
  const out = file.replace(/\.svg$/, ".png");
  await sharp(path.join(blogDir, file), { density: 144 })
    .resize(OG_SIZE.width, OG_SIZE.height)
    .png({ compressionLevel: 9, palette: true, quality: 90 })
    .toFile(path.join(blogDir, out));
  console.log("wrote public/blog/" + out);
}

// 3. Dark-theme copies of the blog SVGs. The light palette maps one-to-one
// onto the dark tokens in globals.css.
const DARK = [
  ["#f7f7f5", "#121211"],
  ["#ffffff", "#1a1a18"],
  ["#eeeeea", "#252522"],
  ["#171716", "#f1f0ea"],
  ["#0d6b4b", "#52c48f"],
  ["#0a563c", "#74d6a8"],
  ["#1a7f4b", "#52c48f"],
  ["rgba(23,23,22,", "rgba(241,240,234,"],
  ["rgba(13,107,75,", "rgba(82,196,143,"],
  ["rgba(26,127,75,", "rgba(82,196,143,"],
];
for (const file of (await readdir(blogDir)).filter(
  (f) => f.endsWith(".svg") && !f.endsWith("-dark.svg"),
)) {
  let svg = await readFile(path.join(blogDir, file), "utf8");
  for (const [from, to] of DARK) svg = svg.split(from).join(to);
  const out = file.replace(/\.svg$/, "-dark.svg");
  await writeFile(path.join(blogDir, out), svg);
  console.log("wrote public/blog/" + out);
}
