"use client";
import { useMemo, useState } from "react";
import { Info } from "lucide-react";

export default function PtaTaxTool() {
  const [usdValue, setUsdValue] = useState("");

  const stats = useMemo(() => {
    const value = parseFloat(usdValue) || 0;
    
    let passportTax = 0;
    let cnicTax = 0;

    if (value === 0) {
      passportTax = 0;
      cnicTax = 0;
    } else if (value <= 30) {
      passportTax = 430;
      cnicTax = 550;
    } else if (value <= 100) {
      passportTax = 3200;
      cnicTax = 4323;
    } else if (value <= 200) {
      passportTax = 9580;
      cnicTax = 11561;
    } else if (value <= 350) {
      passportTax = 12200;
      cnicTax = 14661;
    } else if (value <= 500) {
      passportTax = 27300;
      cnicTax = 31879;
    } else {
      passportTax = 36720 + (value * 278 * 0.18);
      cnicTax = 44723 + (value * 278 * 0.18);
    }

    return {
      passportTax: Math.round(passportTax),
      cnicTax: Math.round(cnicTax),
    };
  }, [usdValue]);

  const formatPKR = (num) =>
    new Intl.NumberFormat("en-PK", {
      style: "currency",
      currency: "PKR",
      maximumFractionDigits: 0,
    }).format(num);

  return (
    <div className="space-y-8">
      <div className="rounded-xl border border-rule bg-bg-2 p-5 sm:p-6">
        <label className="block mb-2 label-sm">
          Enter Phone Value (USD $)
        </label>
        <div className="relative max-w-md">
          <span className="absolute left-4 top-1/2 -translate-y-1/2 text-ink-3 font-medium">
            $
          </span>
          <input
            type="number"
            value={usdValue}
            onChange={(e) => setUsdValue(e.target.value)}
            className="w-full rounded-lg border border-rule bg-bg py-2.5 pl-9 pr-4 text-ink focus:border-accent/50 focus:outline-none"
            placeholder="e.g. 999"
          />
        </div>
      </div>

      <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
        <div className="rounded-xl border border-rule bg-bg p-5 sm:p-6">
          <h3 className="label mb-6">
            On Passport (Baggage Rule)
          </h3>
          <div className="space-y-4">
            <div className="flex justify-between items-center pt-2">
              <span className="text-base text-ink font-semibold">Total Tax</span>
              <span className="font-mono text-xl text-accent font-bold">
                {formatPKR(stats.passportTax)}
              </span>
            </div>
            <p className="text-xs text-ink-3">
              Must be paid within 60 days of arrival in Pakistan.
            </p>
          </div>
        </div>

        <div className="rounded-xl border border-rule bg-bg p-5 sm:p-6">
          <h3 className="label mb-6">
            On CNIC
          </h3>
          <div className="space-y-4">
            <div className="flex justify-between items-center pt-2">
              <span className="text-base text-ink font-semibold">Total Tax</span>
              <span className="font-mono text-xl text-accent font-bold">
                {formatPKR(stats.cnicTax)}
              </span>
            </div>
            <p className="text-xs text-ink-3">
              Standard commercial rate for local registration.
            </p>
          </div>
        </div>
      </div>

      <div className="rounded-lg bg-bg-2 px-4 py-3 flex items-start gap-3 border border-rule">
        <Info className="w-5 h-5 text-ink-3 shrink-0 mt-0.5" />
        <p className="text-sm text-ink-2 leading-relaxed">
          <strong>Disclaimer:</strong> Tax values are estimated based on FBR&apos;s published slab rates and approximate USD to PKR conversion for devices above $500. Actual tax generated by the DIRBS system may slightly vary based on the daily exchange rate and exact phone model.
        </p>
      </div>
    </div>
  );
}
